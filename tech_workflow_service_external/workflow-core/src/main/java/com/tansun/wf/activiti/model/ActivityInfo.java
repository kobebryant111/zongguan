package com.tansun.wf.activiti.model;

public class ActivityInfo {
	   /**
	    * 活动节点ID
	    */
	   private   String  id;
	   
	   /**
	    * 活动节点名称
	    */
	   private   String  name;

	public String getId() {
		return id;
	}

	public void setId(String id) {
		this.id = id;
	}

	public String getName() {
		return name;
	}

	public void setName(String name) {
		this.name = name;
	}
	   
	   
	   

}
