package com.tansun.wf.platform.model;

public class WfTreeNode {

	 private String  pid;
	  
	 private String  id;
	  
	 private  String  name;

	public String getPid() {
		return pid;
	}

	public void setPid(String pid) {
		this.pid = pid;
	}

	public String getId() {
		return id;
	}

	public void setId(String id) {
		this.id = id;
	}

	public String getName() {
		return name;
	}

	public void setName(String name) {
		this.name = name;
	}
	 
}
